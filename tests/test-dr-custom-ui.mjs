import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {loadApp} from './load-app.mjs';
const b=await chromium.launch({executablePath:process.env.CHROME_BINARY});
try {
  const p=await b.newPage({viewport:{width:393,height:852}}),errors=[];
  p.on('pageerror',e=>errors.push(e.message));
  await p.route('https://shottime.local/**',async r=>r.fulfill({body:await loadApp(),contentType:'text/html'}));
  await p.goto('https://shottime.local/');
  const open=async()=>{await p.locator('#app-menu-button').click();await p.locator('#nav-custom').click();};
  const calculate=()=>p.locator('#custom-form button').click();
  await open();await p.locator('#custom-film').selectOption('dr3543pe');
  assert.ok(await p.locator('#custom-dr').isVisible());
  assert.ok(await p.locator('#custom-density').isHidden());
  assert.ok(await p.locator('#custom-pmt').isHidden());
  assert.deepEqual(await p.locator('#custom-dr-pixel option').evaluateAll(opts=>opts.map(o=>o.value)),['3000','6000','9000','12000','15000','18000','21000']);
  assert.equal(await p.locator('#custom-dr-pixel').inputValue(),'3000');
  assert.equal(await p.locator('#custom-dr-frames').inputValue(),'9');
  assert.match(await p.locator('label[for=custom-sfd]').textContent(),/detector/);
  await p.locator('#custom-steel').fill('.5');await p.locator('#custom-sfd').fill('24');
  await p.locator('#custom-use-source').uncheck();await p.locator('#custom-ci').fill('50');await calculate();
  const perFrame=await p.locator('#custom-time').textContent();
  assert.equal(perFrame,'1.229 s');
  assert.match(await p.locator('#custom-dr-total').textContent(),/11.06 s.*9 frames/);
  await p.locator('#custom-dr-frames').selectOption('32');
  assert.ok(await p.locator('#custom-result').isHidden());await calculate();
  assert.equal(await p.locator('#custom-time').textContent(),perFrame);
  assert.match(await p.locator('#custom-dr-total').textContent(),/39.32 s.*32 frames/);
  await p.locator('#custom-dr-pixel').selectOption('6000');await calculate();
  assert.match(await p.locator('#custom-factor').textContent(),/Published 6000-pixel.*0.02370 R/);
  await p.locator('#custom-dr-pixel').selectOption('21000');await calculate();
  assert.match(await p.locator('#custom-factor').textContent(),/Published 21000-pixel.*0.09180 R/);
  await p.locator('#custom-dr-frames').selectOption('custom');
  for(const invalid of ['','0','1.5','1000']){await p.locator('#custom-dr-count').fill(invalid);await calculate();assert.match(await p.locator('#custom-error').textContent(),/frame count/);assert.ok(await p.locator('#custom-result').isHidden());}
  await p.locator('#custom-dr-count').fill('12');await calculate();
  const inchResult=await p.locator('#custom-time').textContent();
  await p.locator('#custom-units').selectOption('mm');await calculate();
  assert.equal(await p.locator('#custom-time').textContent(),inchResult);
  await p.getByText('Saved setups',{exact:true}).click();await p.locator('#custom-preset-name').fill('DR 12 frames');await p.locator('#custom-save').click();
  assert.match(await p.locator('#custom-save-status').textContent(),/saved/);
  await p.reload();await open();await p.getByText('Saved setups',{exact:true}).click();await p.locator('#custom-presets').selectOption('0');await p.locator('#custom-load').click();
  assert.equal(await p.locator('#custom-dr-pixel').inputValue(),'21000');
  assert.equal(await p.locator('#custom-dr-frames').inputValue(),'custom');
  assert.equal(await p.locator('#custom-dr-count').inputValue(),'12');
  assert.ok(await p.locator('#custom-use-source').isChecked());
  await p.locator('#custom-use-source').uncheck();await p.locator('#custom-ci').fill('50');await calculate();
  assert.equal(await p.locator('#custom-time').textContent(),inchResult);
  await p.screenshot({path:'build/dr-custom-mobile.png',fullPage:true});
  await p.setViewportSize({width:320,height:852});assert.ok(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await p.locator('#custom-film').selectOption('t200');await calculate();
  assert.ok(await p.locator('#custom-dr').isHidden());assert.ok(await p.locator('#custom-dr-total').isHidden());
  assert.equal(await p.locator('#custom-time-heading').textContent(),'Estimated exposure');
  await p.evaluate(()=>{const key='shottime.customShots.v1',saved=JSON.parse(localStorage.getItem(key));saved.presets[0].pixel=4000;localStorage.setItem(key,JSON.stringify(saved));});
  await p.reload();await open();await p.getByText('Saved setups',{exact:true}).click();await p.locator('#custom-presets').selectOption('0');await p.locator('#custom-load').click();
  assert.equal(await p.locator('#custom-dr-pixel').inputValue(),'');
  assert.match(await p.locator('#custom-save-status').textContent(),/choose a published pixel target/);
  await p.locator('#custom-use-source').uncheck();await p.locator('#custom-ci').fill('50');await calculate();
  assert.match(await p.locator('#custom-error').textContent(),/published DR pixel target/);
  assert.ok(await p.locator('#custom-result').isHidden());
  assert.deepEqual(errors,[]);
  console.log('PASS: DR controls, frame totals, published factors, legacy preset reselection, validation, units, presets and mobile layout');
} finally {await b.close();}

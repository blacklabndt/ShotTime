import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {loadApp} from './load-app.mjs';
const browser=await chromium.launch({executablePath:process.env.CHROME_BINARY});
try{
 const page=await browser.newPage({viewport:{width:393,height:852}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.route('https://shottime.local/**',async r=>r.fulfill({body:await loadApp(),contentType:'text/html'}));
 await page.goto('https://shottime.local/');
 await page.locator('#app-menu-button').click();
 assert.equal(await page.locator('#nav-unsharpness').count(),1,'Unsharpness is available in the menu');
 await page.locator('#nav-unsharpness').click();
 assert.ok(await page.locator('#unsharpness').isVisible());
 assert.ok(!await page.locator('#calculator-screen').isVisible());
 await page.locator('#ug-unit').selectOption('mm');
 for(const [id,value] of [['source','3'],['distance','600'],['gap','25'],['thickness','25']])await page.locator('#ug-'+id).fill(value);
 await page.locator('#ug-calculate').click();
 assert.match(await page.locator('#ug-value').textContent(),/0\.125 mm/);
 assert.equal(await page.locator('#ug-status').textContent(),'Within recommended limit');
 assert.match(await page.locator('#ug-margin').textContent(),/0\.385 mm/);
 assert.match(await page.locator('#ug-explanation').textContent(),/not a standalone pass\/fail/);
 await page.locator('#ug-distance').fill('100');await page.locator('#ug-calculate').click();
 assert.equal(await page.locator('#ug-status').textContent(),'Exceeds recommended limit');
 assert.match(await page.locator('#ug-margin').textContent(),/0\.24 mm/);
 assert.match(await page.locator('#ug-adjustment').textContent(),/Increase source distance.*147\.059 mm.*172\.059 mm/);
 await page.locator('#ug-source').fill('3.06');await page.locator('#ug-distance').fill('150');await page.locator('#ug-calculate').click();
 assert.equal(await page.locator('#ug-status').textContent(),'Within recommended limit');
 assert.match(await page.locator('#ug-margin').textContent(),/^0 mm/);
 await page.locator('#ug-source').fill('3');await page.locator('#ug-distance').fill('600');await page.locator('#ug-calculate').click();
 await page.locator('#ug-unit').selectOption('in');
 assert.ok(Math.abs(Number(await page.locator('#ug-distance').inputValue())-23.622047244094)<1e-9);
 assert.ok(!await page.locator('#ug-result').isVisible(),'Changing inputs clears stale results');
 await page.locator('#ug-calculate').click();
 assert.match(await page.locator('#ug-value').textContent(),/0\.125 mm/);
 await page.locator('#ug-source').fill('bad');await page.locator('#ug-calculate').click();
 assert.ok(!await page.locator('#ug-result').isVisible());assert.match(await page.locator('#ug-error').textContent(),/source size/);
 await page.locator('#ug-unit').selectOption('mm');await page.locator('#ug-source').fill('3');
 await page.locator('#ug-code').selectOption('csa-sour');
 assert.ok(!await page.locator('#ug-thickness').isVisible());
 await page.locator('#ug-distance').fill('150');await page.locator('#ug-gap').fill('25');await page.locator('#ug-calculate').click();
 assert.match(await page.locator('#ug-status').textContent(),/Meets.*7/);
 assert.match(await page.locator('#ug-actual-distance').textContent(),/^175 mm/);
 assert.match(await page.locator('#ug-minimum-distance').textContent(),/^175 mm/);
 assert.match(await page.locator('#ug-preferred-distance').textContent(),/^250 mm/);
 assert.match(await page.locator('#ug-adjustment').textContent(),/Minimum met.*250 mm/);
 await page.locator('#ug-distance').fill('100');await page.locator('#ug-calculate').click();
 assert.equal(await page.locator('#ug-status').textContent(),'Source distance is too short');
 await page.locator('#ug-distance').fill('225');await page.locator('#ug-calculate').click();
 assert.equal(await page.locator('#ug-preferred-status').textContent(),'Preferred distance reached');
 await page.locator('#ug-distance').fill('150');await page.locator('#ug-calculate').click();
 await page.locator('#ug-unit').selectOption('in');await page.locator('#ug-calculate').click();
 assert.match(await page.locator('#ug-status').textContent(),/Meets.*7/,'Unit conversion must preserve a boundary result');
 await page.locator('#ug-unit').selectOption('mm');
 assert.match(await page.locator('#ug-reference').textContent(),/7\.14\.2/);
 await page.locator('#ug-code').selectOption('viii');await page.locator('#ug-medium').selectOption('cr');
 assert.match(await page.locator('#ug-reference').textContent(),/VIII-210/);
 await page.locator('#ug-code').selectOption('b311');await page.locator('#ug-calculate').click();
 assert.match(await page.locator('#ug-limit').textContent(),/2 mm/);
 assert.equal(await page.locator('#ug-status').textContent(),'Within code Ug limit');
 await page.locator('#ug-distance').fill('25');await page.locator('#ug-calculate').click();
 assert.equal(await page.locator('#ug-status').textContent(),'Exceeds code Ug limit');
 assert.match(await page.locator('#ug-adjustment').textContent(),/source to plate/);
 for(const width of [320,393,430]){await page.setViewportSize({width,height:852});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));}
 await page.screenshot({path:'build/unsharpness-preview.png',fullPage:true});
 assert.equal(await page.evaluate(()=>closeTopSheet()),true);assert.ok(await page.locator('#calculator-screen').isVisible());
 assert.deepEqual(errors,[]);
 console.log('Unsharpness mobile UI, conversions, references, stale results, validation and Back passed.');
}finally{await browser.close();}

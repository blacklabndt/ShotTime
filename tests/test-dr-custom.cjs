const assert=require('node:assert/strict');
const C=require('../assets/calculator.js');
const near=(a,b)=>assert.ok(Math.abs(a-b)<1e-10*Math.max(1,b),`${a} != ${b}`);
near(C.drRFactor(3000),.0112);
const published={3000:.0112,6000:.0237,9000:.0366,12000:.0499,15000:.0635,18000:.0775,21000:.0918};
assert.deepEqual(C.DR_R_FACTORS,published);
for(const [pixel,dose] of Object.entries(published))near(C.drRFactor(Number(pixel)),dose);
const a=C.drShot(.5,24,3000,9,50);
near(a.perFrameSeconds,.0112*(24*.0254)**2*3600/.48/50*2**(12.7/13));
near(a.totalSeconds,a.perFrameSeconds*9);
near(C.drShot(.5,48,3000,1,50).perFrameSeconds,a.perFrameSeconds*4);
near(C.drShot(.5,24,3000,32,100).perFrameSeconds,a.perFrameSeconds/2);
near(C.drShot(.5+13/25.4,24,3000,1,50).perFrameSeconds,a.perFrameSeconds*2);
for(const pixel of [2000,4000,5999,21001,24000,NaN,Infinity,'3000'])assert.throws(()=>C.drRFactor(pixel));
for(const frames of [0,-1,1.5,1000,NaN,'9'])assert.throws(()=>C.drShot(.5,24,3000,frames,50));
for(const ci of [0,-1,NaN,Infinity])assert.throws(()=>C.drShot(.5,24,3000,9,ci));
assert.throws(()=>C.drShot(4,24,3000,9,50));
assert.equal(C.usesDensity('dr3543pe'),false);
assert.ok(C.CUSTOM_FILMS.includes('dr3543pe'));
near(C.customExposure(.5,24,'dr3543pe',null,{pixel:3000}),a.perFrameSeconds*50);
console.log('PASS: independent DR dose, geometry/activity scaling, frame totals and invalid inputs');
